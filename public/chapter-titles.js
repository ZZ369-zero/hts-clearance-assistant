const chapterTitlesByCode = new Map(chapterTitleCatalog.map(([code, titleZh, titleEn]) => [
  code,
  { code, titleZh, titleEn }
]));

export function getChapterTitle(code, fallbackEn = "", fallbackZh = "") {
  const normalizedCode = String(code || "").padStart(2, "0");
  const known = chapterTitlesByCode.get(normalizedCode);
  return {
    code: normalizedCode,
    titleZh: fallbackZh || known?.titleZh || "未命名章节",
    titleEn: fallbackEn || known?.titleEn || "Untitled chapter"
  };
}
